# Фойдаланувчиларнинг қайси саволда турганини сақлаш
user_state = {}

@bot.message_handler(commands=['start', 'test'])
def start_quiz(message):
    chat_id = message.chat.id
    user_state[chat_id] = 0  # 0-саволдан бошлаймиз
    send_next_question(chat_id)

def send_next_question(chat_id):
    index = user_state.get(chat_id, 0)
    
    if index < len(QUIZ_DATA):
        q = QUIZ_DATA[index]
        bot.send_poll(
            chat_id=chat_id,
            question=q["question"],
            options=q["options"],
            type='quiz',
            correct_option_id=q["correct"],
            is_anonymous=False,
            explanation=q["explanation"]
        )
    else:
        bot.send_message(
            chat_id, 
            "🎉 Барча тестларни муваффақиятли тамомладингиз!\n\nҚайтадан бошлаш учун /test буйруғини юборинг."
        )

@bot.poll_answer_handler()
def handle_poll_answer(poll_answer):
    chat_id = poll_answer.user.id
    if chat_id in user_state:
        user_state[chat_id] += 1
        send_next_question(chat_id)

if __name__ == "__main__":
    print("Бот тестлар билан ишга тушди...")
    bot.infinity_polling()
